// GOD-6: the GitHub requests only an App may make. With "Act as me" on, every other request is sent with the person's
// master token; these always stay on the app. Generated from the capability inventory (every operation whose classic-token
// disposition is "unsupported") plus a fixed list the inventory marks "unknown" but GitHub's documentation reserves for Apps:
//   https://docs.github.com/en/rest/checks/runs  and  https://docs.github.com/en/rest/checks/suites
// (re-read 2026-10-24: create/update check run and create check suite state classic tokens cannot use them; the other
// check endpoints are kept on the app because writing checks is documented as "only available to GitHub Apps").
// Run `node scripts/build-app-only-routes.mjs` to rewrite src/github/app-only-routes.js; a unit test keeps it in sync.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildCapabilityInventory } from '../src/github/capability-inventory.js';

export const FIXED = Object.freeze([
  'POST /repos/{owner}/{repo}/check-runs',
  'PATCH /repos/{owner}/{repo}/check-runs/{check_run_id}',
  'POST /repos/{owner}/{repo}/check-runs/{check_run_id}/rerequest',
  'POST /repos/{owner}/{repo}/check-suites',
  'PATCH /repos/{owner}/{repo}/check-suites/preferences',
  'POST /repos/{owner}/{repo}/check-suites/{check_suite_id}/rerequest',
  'POST /app-manifests/{code}/conversions'
]);

export function buildAppOnlyRoutes() {
  const inventory = buildCapabilityInventory({ registryTools: [] });
  const fromInventory = inventory.operations
    .filter((o) => o.credentialSupport?.classic_pat?.disposition === 'unsupported')
    .map((o) => `${o.operation.method} ${o.operation.path}`);
  return [...new Set([...fromInventory, ...FIXED])].sort();
}

export function render(routes) {
  return `// GENERATED by scripts/build-app-only-routes.mjs (GOD-6). Do not edit by hand; run the script.
// Requests an App must make itself: with "Act as me" on, everything else is sent as the person.
export const APP_ONLY = Object.freeze([
${routes.map((r) => `  '${r}'`).join(',\n')}
]);

/** GraphQL mutations only an App may run. */
export const APP_ONLY_GRAPHQL = Object.freeze(['createCheckRun', 'updateCheckRun', 'createCheckSuite', 'rerequestCheckSuite']);

/** Every path starting with this belongs to the installation token alone. */
export const APP_ONLY_PREFIXES = Object.freeze(['/installation/']);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../src/github/app-only-routes.js', import.meta.url), render(buildAppOnlyRoutes()));
  console.log('wrote src/github/app-only-routes.js');
}
